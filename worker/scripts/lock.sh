#!/usr/bin/env bash
# Regenerates the hashed lockfiles inside the pinned production Python image (needs
# PyPI access). Run after changing [project].dependencies or the build backend pin:
#   bash worker/scripts/lock.sh
# requirements.lock        runtime deps of the image (pip install --require-hashes --no-deps)
# requirements-build.lock  build backend used to build the sentinela-worker wheel
set -euo pipefail

PY_TAG="3.12.16-slim"   # keep in sync with worker/Dockerfile and scripts/test.sh
UV_VERSION="0.13.9"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# compile <uv pip compile args...>: hashed, fully pinned requirements on stdout.
compile() {
  docker run --rm -i -v "$HERE/pyproject.toml:/w/pyproject.toml:ro" -w /w "python:${PY_TAG}" sh -ec \
    "pip install -q --disable-pip-version-check --root-user-action=ignore uv==${UV_VERSION} >&2
     exec uv pip compile \"\$@\" --generate-hashes --no-header --quiet" uv "$@"
}

# write <file> <description> <uv pip compile args...>
write() {
  local file=$1 what=$2 tmp
  shift 2
  tmp=$(mktemp "$HERE/.lock.XXXXXX")
  {
    printf '# %s. Generated by worker/scripts/lock.sh; do not edit by hand.\n' "$what"
    printf '# Exact command (in python:%s, uv %s):\n' "$PY_TAG" "$UV_VERSION"
    printf '#   uv pip compile %s --generate-hashes --no-header\n' "$*"
    compile "$@"
  } >"$tmp" || { rm -f "$tmp"; exit 1; }
  mv -f "$tmp" "$HERE/$file"
}

write requirements.lock "Runtime dependencies of the worker image (pip install --require-hashes --no-deps)" pyproject.toml
printf 'setuptools==80.9.0\n' | write requirements-build.lock "Build backend for the sentinela-worker wheel; stdin is the single line setuptools==80.9.0 ([build-system] pin)" -
